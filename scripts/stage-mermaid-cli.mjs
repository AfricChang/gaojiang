import childProcess from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const distDir = path.join(repoRoot, "dist-cli");
const resourcesDir = path.join(repoRoot, "src-tauri", "resources");
const runtimeDir = path.join(resourcesDir, "mermaid-cli");
const appDir = path.join(runtimeDir, "app");
const launcherPath = path.join(resourcesDir, "wenyan-mermaid.cmd");

function run(command, args, options = {}) {
    const result = childProcess.spawnSync(command, args, {
        shell: process.platform === "win32",
        stdio: "inherit",
        ...options,
    });

    if (result.status !== 0) {
        if (result.error) {
            throw result.error;
        }
        throw new Error(`${command} ${args.join(" ")} failed with exit code ${result.status ?? "unknown"}.`);
    }
}

async function readInstalledPackageVersion(packageName) {
    const packageJsonPath = path.join(repoRoot, "node_modules", packageName, "package.json");
    const packageJson = JSON.parse(await fs.readFile(packageJsonPath, "utf8"));
    if (!packageJson.version) {
        throw new Error(`Unable to read installed version for ${packageName}.`);
    }
    return packageJson.version;
}

async function assertBuiltCliExists() {
    const entryPath = path.join(distDir, "scripts", "mermaid-export.js");
    await fs.access(entryPath);
}

async function writeRuntimePackage() {
    const runtimePackageJson = {
        private: true,
        type: "module",
        dependencies: {
            mermaid: await readInstalledPackageVersion("mermaid"),
            playwright: await readInstalledPackageVersion("playwright"),
        },
    };

    await fs.writeFile(path.join(appDir, "package.json"), `${JSON.stringify(runtimePackageJson, null, 2)}\n`, "utf8");
}

async function writeLauncher() {
    const launcher = [
        "@echo off",
        "setlocal",
        "",
        "set \"SCRIPT_DIR=%~dp0\"",
        "set \"NODE_NO_WARNINGS=1\"",
        "\"%SCRIPT_DIR%mermaid-cli\\node.exe\" \"%SCRIPT_DIR%mermaid-cli\\app\\scripts\\mermaid-export.js\" %*",
        "exit /b %ERRORLEVEL%",
        "",
    ].join("\r\n");

    await fs.writeFile(launcherPath, launcher, "utf8");
}

async function writeRuntimeReadme() {
    const readme = [
        "# Wenyan Mermaid CLI Runtime",
        "",
        "This directory is generated by `pnpm cli:stage` and bundled with the Wenyan desktop application.",
        "",
        "Use `..\\wenyan-mermaid.cmd` from the installed application resources directory.",
        "",
        "The CLI exports Mermaid diagrams from `.md`, `.markdown`, and `.mmd` files to SVG or PNG.",
        "The same runtime is also used by the desktop application for PDF export.",
        "",
        "It uses the system Microsoft Edge or Google Chrome browser for headless rendering.",
        "",
    ].join("\n");

    await fs.writeFile(path.join(runtimeDir, "README.md"), readme, "utf8");
}

if (process.platform !== "win32") {
    console.log("Skipping Wenyan Mermaid CLI staging because the product CLI is currently Windows-only.");
    process.exit(0);
}

await assertBuiltCliExists();
await fs.mkdir(appDir, { recursive: true });
await fs.cp(distDir, appDir, { recursive: true });
await fs.copyFile(process.execPath, path.join(runtimeDir, "node.exe"));
await writeRuntimePackage();
await writeLauncher();
await writeRuntimeReadme();

const pnpmCommand = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
run(pnpmCommand, [
    "install",
    "--prod",
    "--ignore-scripts",
    "--ignore-workspace",
    "--no-lockfile",
    "--config.node-linker=hoisted",
    "--config.package-import-method=copy",
], {
    cwd: appDir,
    env: {
        ...process.env,
        PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD: "1",
    },
});

console.log(`Staged Wenyan Mermaid CLI runtime at ${runtimeDir}`);
console.log(`Launcher: ${launcherPath}`);
